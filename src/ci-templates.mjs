/** Renders one GitHub Actions step block at four-space indentation. */
function renderGhStep(step) {
  const lines = [`      - name: ${step.name}`, `        uses: ${step.uses}`];
  if (step.with) {
    lines.push(`        with:`);
    for (const [k, v] of Object.entries(step.with)) lines.push(`          ${k}: "${v}"`);
  }
  return lines.join("\n");
}

const HEADER = (stack, version) =>
  `# Generated by jules-orchestrator-kit v${version} for a '${stack}' project.
#
# This file is yours now — edit it freely. Two things worth doing before you
# rely on it:
#   1. Pin each third-party action to a commit SHA (a tag can be moved).
#   2. Check that the runtime versions below match what the project targets.
#
# Regenerate with: agentctl ci init --force
`;

/**
 * @param {object} opts
 * @param {string} opts.target - "github" | "gitlab"
 * @param {{stack: string}} opts.stack - result of detectStack()
 * @param {object} [opts.config] - loaded config, for base_branch
 * @param {string} [opts.version]
 * @returns {{ file: string, content: string, setupSummary: string }}
 */
export function buildCiWorkflow(opts = {}) {
  const target = CI_TARGETS.includes(opts.target) ? opts.target : "github";
  const stackId = opts.stack?.stack || "unknown";
  const base = opts.config?.baseBranch || "main";
  const version = opts.version || "0";
  const toolchain = STACK_TOOLCHAINS[stackId] || null;
  const setupSummary = toolchain ? toolchain.label : "Node only";

  if (target === "gitlab") {
    const image = toolchain?.gl || "node:20";
    const needsNode = image !== "node:20" && !image.startsWith("node");
    const content = `${HEADER(stackId, version)}
agent-gate:
  image: ${image}
  stage: test
  variables:
    GIT_DEPTH: "0"
  rules:
    - if: $CI_PIPELINE_SOURCE == "merge_request_event"
    - if: $CI_COMMIT_BRANCH == "${base}"
  script:${
    needsNode
      ? `
    # agentctl is a Node CLI, so the image needs Node even when the project is not.
    - command -v node >/dev/null 2>&1 || (apt-get update -qq && apt-get install -y -qq nodejs npm)`
      : ""
  }
    - npx --yes jules-orchestrator-kit check --mode committed --base "origin/${base}"
`;
    return { file: ".gitlab-ci.agent-gate.yml", content, setupSummary };
  }

  const extraSteps = (toolchain?.gh || []).map(renderGhStep).join("\n");
  const content = `${HEADER(stackId, version)}
name: Agent Safety Gate

on:
  pull_request:
    branches: [ ${base} ]
  push:
    branches: [ ${base} ]

permissions:
  contents: read

jobs:
  gate:
    runs-on: ubuntu-latest
    timeout-minutes: 20
    steps:
      - name: Checkout repository
        uses: actions/checkout@v4
        with:
          # The gate compares the branch against its merge base, which needs
          # full history rather than the default single-commit fetch.
          fetch-depth: 0
          persist-credentials: false

      # agentctl is a Node CLI: the runner needs Node whatever the project is
      # written in.
      - name: Set up Node.js
        uses: actions/setup-node@v4
        with:
          node-version: "20"
${extraSteps ? extraSteps + "\n" : ""}
      - name: Run agent safety gate
        run: npx --yes jules-orchestrator-kit check --mode committed --base "origin/${base}"
`;
  return { file: ".github/workflows/agent-gate.yml", content, setupSummary };
}

/**
 * Generate a workflow_run auto-merge workflow for GitHub Actions that safely
 * merges qualifying green PRs opened by authorized automation bots.
 *
 * Implements a strict trust boundary:
 * - Executes exclusively on the base branch (default `main`)
 * - Evaluates PR commits strictly as unexecuted data (fetch + git diff)
 * - Verifies the bot actor against authorized identities (default `google-labs-jules[bot]`)
 * - Merges cleanly via `gh pr merge --squash --delete-branch`
 *
 * @param {object} opts
 * @param {object} [opts.config]
 * @param {string} [opts.version]
 * @param {string[]} [opts.allowedActors]
 * @returns {{ file: string, content: string }}
 */
export function buildAutoMergeWorkflow(opts = {}) {
  const base = opts.config?.baseBranch || opts.baseBranch || "main";
  const version = opts.version || "0";
  const defaultActors = ["google-labs-jules[bot]", "github-actions[bot]"];
  const allowedActors = opts.allowedActors || defaultActors;
  const actorCases = allowedActors.map((a) => `"${a}"`).join("|");

  const content = `# Generated by jules-orchestrator-kit v${version}.
#
# Auto-merge verified pull requests opened by authorized automation bots.
#
# TRUST BOUNDARY ARCHITECTURE:
#   For pull requests from repository branches, GitHub Actions runs
#   'on: pull_request' workflows from the PR branch head. A pull request can
#   therefore supply its own modified workflow code.
#
#   This workflow runs on 'workflow_run' after 'Agent Safety Gate' completes.
#   It executes STRICTLY from the default branch (${base}), ensuring that:
#   1. It only runs code, scripts, and policies committed to ${base}.
#   2. The pull request commits are fetched strictly as unexecuted data.
#   3. Privileged write tokens are never exposed to the untrusted PR branch.
#
# Regenerate with: agentctl ci init --with-automerge --force

name: Agent Auto-Merge

on:
  workflow_run:
    workflows: ["Agent Safety Gate"]
    types: [completed]

permissions:
  contents: read

concurrency:
  group: agent-automerge-\${{ github.event.workflow_run.head_sha }}
  cancel-in-progress: false

jobs:
  automerge:
    if: >-
      github.event.workflow_run.conclusion == 'success' &&
      github.event.workflow_run.event == 'pull_request' &&
      github.event.workflow_run.head_repository.full_name == github.repository
    runs-on: ubuntu-latest
    permissions:
      contents: write
      pull-requests: write
    env:
      GH_TOKEN: \${{ secrets.GITHUB_TOKEN }}
      REPO: \${{ github.repository }}
      HEAD_SHA: \${{ github.event.workflow_run.head_sha }}
      ACTOR: \${{ github.event.workflow_run.actor.login }}
    steps:
      - name: Checkout base revision (${base})
        uses: actions/checkout@v4
        with:
          ref: ${base}
          fetch-depth: 0
          persist-credentials: false

      - name: Verify authorized automation actor
        run: |
          set -euo pipefail
          case "$ACTOR" in
            ${actorCases})
              echo "Authorized automation actor: $ACTOR"
              ;;
            *)
              echo "Actor '$ACTOR' is not an authorized automation bot; leaving PR for human review."
              exit 0
              ;;
          esac

      - id: pr
        name: Resolve Pull Request
        run: |
          set -euo pipefail
          num=$(gh pr list --repo "$REPO" --state open --base "${base}" \\
                  --json number,headRefOid \\
                  --jq "[.[] | select(.headRefOid == \\"$HEAD_SHA\\")] | .[0].number // empty")
          if [ -z "$num" ]; then
            echo "No open PR found for head SHA $HEAD_SHA; nothing to merge."
            echo "found=false" >> "$GITHUB_OUTPUT"
            exit 0
          fi
          echo "Resolved PR #$num for $HEAD_SHA"
          echo "number=$num" >> "$GITHUB_OUTPUT"
          echo "found=true" >> "$GITHUB_OUTPUT"

      - name: Fetch PR commits as untrusted data
        if: steps.pr.outputs.found == 'true'
        run: |
          set -euo pipefail
          git fetch --no-tags origin "+$HEAD_SHA:refs/pr-head"

      - name: Set up Node.js
        if: steps.pr.outputs.found == 'true'
        uses: actions/setup-node@v4
        with:
          node-version: "20"

      - name: Verify safety gate from base
        if: steps.pr.outputs.found == 'true'
        run: |
          npx --yes jules-orchestrator-kit check --mode committed --base "${base}"

      - name: Squash and merge pull request
        if: steps.pr.outputs.found == 'true'
        run: |
          gh pr merge --squash --delete-branch "\${{ steps.pr.outputs.number }}" --repo "$REPO"
`;

  return { file: ".github/workflows/agent-automerge.yml", content };
}

/**
 * Write the generated workflow(s), refusing to clobber existing files unless
 * asked.
 *
 * @param {string} root
 * @param {object} [opts] - see {@link buildCiWorkflow}, plus `force`, `dryRun`, and `withAutomerge`
 * @returns {{ ok: boolean, file?: string, files?: string[], written?: boolean, stack?: string, setupSummary?: string, content?: string, error?: string }}
 */
export function writeCiWorkflow(root, opts = {}) {
  const target = CI_TARGETS.includes(opts.target) ? opts.target : (opts.target ? opts.target : "github");
  if (opts.target && !CI_TARGETS.includes(opts.target)) {
    return { ok: false, error: `Unknown CI target '${opts.target}'. Choose one of: ${CI_TARGETS.join(", ")}` };
  }

  const withAutomerge = Boolean(opts.withAutomerge || opts["with-automerge"]);
  if (withAutomerge && target !== "github") {
    return { ok: false, error: "Auto-merge workflow is currently only supported for GitHub Actions." };
  }

  const built = buildCiWorkflow(opts);
  const stackId = opts.stack?.stack || "unknown";
  const itemsToWrite = [built];

  if (withAutomerge) {
    itemsToWrite.push(buildAutoMergeWorkflow(opts));
  }

  const files = itemsToWrite.map((item) => item.file);

  if (opts.dryRun) {
    return {
      ok: true,
      file: built.file,
      files,
      written: false,
      stack: stackId,
      setupSummary: built.setupSummary,
      content: built.content,
      workflows: itemsToWrite,
    };
  }

  let allWritten = true;
  let allIdentical = true;
  for (const item of itemsToWrite) {
    const abs = join(root, item.file);
    if (existsSync(abs) && !opts.force) {
      let identical = false;
      try {
        identical = readFileSync(abs, "utf-8") === item.content;
      } catch (_) {
        // Unreadable target: treat as different so the caller is told to --force
        // rather than being told nothing changed.
      }
      if (!identical) {
        allIdentical = false;
      }
      allWritten = false;
      continue;
    }

    try {
      mkdirSync(dirname(abs), { recursive: true });
      writeFileSync(abs, item.content, "utf-8");
    } catch (err) {
      return { ok: false, error: `Could not write ${item.file}: ${err.message}` };
    }
  }

  return {
    ok: true,
    file: built.file,
    files,
    written: allWritten,
    identical: allWritten ? false : allIdentical,
    stack: stackId,
    setupSummary: built.setupSummary,
    content: built.content,
  };
}
